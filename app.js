function escapeHTML(value) {
  return String(value).replace(/[&<>'"]/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', "'": '&#39;', '"': '&quot;' }[char]));
}

function formatTime(date = new Date()) {
  return new Intl.DateTimeFormat('zh-CN', { hour: '2-digit', minute: '2-digit', hour12: false }).format(date);
}

function saveState() {
  if (state.ticket) {
    const index = state.tickets.findIndex(ticket => ticket.id === state.ticket.id);
    if (index >= 0) state.tickets[index] = state.ticket;
    else state.tickets.push(state.ticket);
  }
  try { localStorage.setItem('xiaoqi-it-demo', JSON.stringify(state)); } catch (_) {
    if (!storageWarningShown) toast('浏览器存储空间不足或不可用，当前内容仅保留到页面关闭，请勿刷新');
    storageWarningShown = true;
  }
  updateSidebar();
}

function upgradeFeedbackMessages(messages) {
  const isOldConfirmation = message => message?.role === 'assistant' && (
    message.html.startsWith('<p>好的，我已记录这一步。<strong>现在问题解决了吗？</strong>') ||
    message.html.startsWith('<p>确认一下：完成第二步检查后，问题是否已经恢复？</p>')
  );
  return messages.filter((message, index) => {
    if (isOldConfirmation(message)) return false;
    // These were generated by the removed completion buttons, not free-form replies.
    const isOldCompletion = message.role === 'user' && [
      '<p>我已经按步骤操作完成了</p>', '<p>已经检查过了</p>'
    ].includes(message.html);
    return !(isOldCompletion && isOldConfirmation(messages[index + 1]));
  }).map(message => {
    if (message.role !== 'assistant') return message;
    return {
      ...message,
      html: message.html
        .replace(/<button\b[^>]*data-action="cannot-do"[^>]*>[\s\S]*?<\/button>/g, '')
        .replace(/(<button\b[^>]*data-action="handoff"[^>]*>)直接转人工(<\/button>)/g, '$1转人工$2')
        .replace(
        /<button class="quick-action primary" data-action="(?:step-done|second-done)">[^<]*<\/button>/g,
        '<button class="quick-action success" data-action="solved">已解决</button><button class="quick-action" data-action="not-solved">仍未解决</button>'
      )
    };
  });
}

function loadState() {
  try {
    const saved = JSON.parse(localStorage.getItem('xiaoqi-it-demo'));
    if (saved && saved.conversationId && Array.isArray(saved.messages)) {
      state = saved;
      state.screenshots = saved.screenshots || [];
      state.troubleshooting = saved.troubleshooting || [];
      state.tickets = Array.isArray(saved.tickets) ? saved.tickets : [];
      if (state.ticket) {
        const stored = state.tickets.find(ticket => ticket.id === state.ticket.id);
        if (stored) state.ticket = stored;
        else {
          state.ticket = { ...state.ticket, draft: { ...state.ticketDraft }, scenario: state.scenario, conversationId: state.conversationId };
          state.tickets.push(state.ticket);
        }
      }
      state.messages = upgradeFeedbackMessages(state.messages);
      try { localStorage.setItem('xiaoqi-it-demo', JSON.stringify(state)); } catch (_) { /* keep the upgraded view in memory */ }
    }
  } catch (_) { state = initialState(); }
}

