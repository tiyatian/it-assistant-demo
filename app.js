function finishWelcomeTyping() {
  clearTimeout(welcomeTimer);
  welcomeTimer = null;
  $('#welcomePrefix').textContent = welcomePrefix;
  $('#welcomeEnding').textContent = welcomeEnding;
  $('#welcomeTitle').classList.remove('is-typing');
}

function playWelcomeTyping() {
  if (welcomePlayed) return;
  welcomePlayed = true;
  if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
  const prefixChars = Array.from(welcomePrefix);
  const endingChars = Array.from(welcomeEnding);
  const length = prefixChars.length + endingChars.length;
  let index = 0;
  $('#welcomePrefix').textContent = '';
  $('#welcomeEnding').textContent = '';
  $('#welcomeTitle').classList.add('is-typing');
  function typeNext() {
    index++;
    $('#welcomePrefix').textContent = prefixChars.slice(0, index).join('');
    $('#welcomeEnding').textContent = endingChars.slice(0, Math.max(0, index - prefixChars.length)).join('');
    if (index < length) welcomeTimer = setTimeout(typeNext, 85);
    else finishWelcomeTyping();
  }
  welcomeTimer = setTimeout(typeNext, 180);
}

