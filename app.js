function detectScenario(text) {
  if (/密码|token|密钥|secret/i.test(text)) return 'sensitive';
  if (/工单.*(进度|状态|怎么样)|处理到哪|ticket/i.test(text)) return 'status';
  if (/人工|提单|创建工单|提交工单/.test(text)) return 'handoff';
  if (/vpn|认证|远程办公/i.test(text)) return 'vpn';
  if (/网络|wifi|wi-fi|上网|联网/i.test(text)) return 'network';
  if (/软件|figma|申请|安装|权限/i.test(text)) return 'software';
  if (/天气|吃饭|写诗|旅游/.test(text)) return 'nonit';
  return 'generic';
}

function beginConversation(text) {
  const value = text.trim();
  if (!value || actionLocked) return;
  if (state.phase === 'welcome') {
    state.phase = 'active';
    state.title = value.length > 24 ? `${value.slice(0, 24)}…` : value;
    state.scenario = detectScenario(value);
    showChat();
  }
  addMessage('user', `<p>${escapeHTML(value)}</p>`);
  $('#conversationTitle').textContent = state.title;
  updateFacts({ '状态': '理解问题' });
  routeUserInput(value);
}

async function routeUserInput(text) {
  if (state.screenshots.length && await routeScreenshotText(text)) return;
  if (state.attempt && !state.ticket && state.phase === 'active') {
    if (/^(已解决|已经解决了?|解决了|好了|恢复了|我已完成)[！!。\s]*$/.test(text)) {
      await markResolved(true);
      return;
    }
    if (/^(仍未解决|未解决|还是不行|没用|没有用|无效|不行)[！!。\s]*$/.test(text)) {
      await handleUnresolved(true);
      return;
    }
  }
  const scenario = detectScenario(text);
  if (scenario === 'sensitive') {
    await assistantReply(`<p>为了保护账号安全，请不要在对话中发送密码、Token 或密钥。我不会记录或复述这类信息。</p><div class="warning-card">${icons.shield}<span><strong>已触发敏感信息保护</strong><br>请只描述错误提示和发生场景，不要提供真实凭据。</span></div><div class="quick-actions"><button class="quick-action" data-action="restart-question">重新描述问题</button><button class="quick-action" data-action="handoff">转人工</button></div>`, 500, 'clarify');
    return;
  }
  if (scenario === 'status') { await showTicketStatus(); return; }
  if (scenario === 'handoff') { await startHandoff('user_request'); return; }
  if (scenario === 'nonit') {
    await assistantReply('<p>我目前主要处理企业 IT 服务问题，例如网络、VPN、账号、软件和设备故障。你可以直接描述遇到的 IT 现象，我来帮你判断下一步。</p>', 500, 'clarify');
    return;
  }
  if (scenario === 'software') {
    state.scenario = 'software';
    state.title = '申请 Figma 专业版软件';
    updateFacts({ '设备': '公司电脑', '问题类型': '软件申请', '状态': '需要人工操作' });
    await assistantReply(`<p>我理解你需要申请 <strong>Figma 专业版</strong>。这涉及软件授权和成本审批，V1 不会自动开通权限，需要由 IT 人员继续处理。</p><p>我已保留你的诉求，你无需重新填写传统工单。</p><div class="knowledge-card"><div class="knowledge-head">${icons.ticket}<div><strong>已匹配企业流程</strong><small>《办公软件申请与授权规范》· 2026-08-15 更新</small></div></div><div class="knowledge-source"><span>IT 官方知识 · 相关度 96%</span><button data-action="source">查看依据</button></div></div><div class="quick-actions"><button class="quick-action primary" data-action="handoff">生成申请工单</button><button class="quick-action" data-action="cancel-handoff">暂不申请</button></div>`, 780, 'result');
    return;
  }
  if (scenario === 'vpn' || scenario === 'network' || scenario === 'generic') {
    state.scenario = scenario === 'generic' ? 'vpn' : scenario;
    const understood = state.scenario === 'network' ? '公司网络连接异常' : state.scenario === 'vpn' ? 'VPN 认证失败' : 'IT 故障';
    updateFacts({ '问题': understood, '状态': '等待环境信息' });
    await assistantReply(`<p>收到。我先确认一个最关键的信息，避免给你不适用的步骤：<strong>这台电脑使用什么系统？</strong></p><div class="quick-actions"><button class="quick-action" data-action="choose-os" data-value="Windows 11">Windows</button><button class="quick-action" data-action="choose-os" data-value="macOS 15">macOS</button><button class="quick-action" data-action="unknown-os">不确定</button></div>`, 720, 'clarify');
  }
}

