document.addEventListener('click', async event => {
  const target = event.target.closest('[data-action]');
  if (!target || target.disabled || actionLocked) return;
  const action = target.dataset.action;
  if (action === 'choose-os') await chooseOS(target.dataset.value);
  else if (action === 'unknown-os') await chooseOS('Windows（根据设置界面判断）');
  else if (action === 'step-done' || action === 'second-done') await markResolved();
  else if (action === 'not-solved') await handleUnresolved();
  else if (action === 'solved') await markResolved();
  else if (action === 'handoff') await startHandoff('user_request');
  else if (action === 'handoff-failed') await handleUnresolved();
  else if (action === 'urgency') await setUrgency(target.dataset.value);
  else if (action === 'edit-ticket') openEditDialog();
  else if (action === 'submit-ticket') await submitTicket(target);
  else if (action === 'refresh-status') await refreshTicketStatus(target.dataset.ticketId || state.ticket?.id);
  else if (action === 'ticket-detail') openTicketDetail(target.dataset.ticketId);
  else if (action === 'query-ticket') await showTicketStatus(target.dataset.ticketId);
  else if (action === 'back-assistant') { if (state.phase === 'welcome') showWelcome(); else showChat(); }
  else if (action === 'source') toast('Demo：将跳转到有权限的企业知识原文');
  else if (action === 'rate') { $$('.rating button').forEach(button => button.classList.toggle('selected', Number(button.dataset.value) <= Number(target.dataset.value))); toast(`感谢你的 ${target.dataset.value} 分评价`); }
  else if (action === 'restart-question') startNewConversation();
  else if (action === 'cancel-handoff') { addMessage('user', '<p>暂不处理</p>'); await assistantReply('<p>好的，本次对话已经保留。需要时可以回来继续，或随时让我帮你创建工单。</p>', 350, 'result'); }
});

