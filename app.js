function autoResize(textarea) {
  textarea.style.height = 'auto';
  textarea.style.height = `${Math.min(textarea.scrollHeight, textarea === heroInput ? 140 : 110)}px`;
}

function handleTextarea(event, sendButton) {
  autoResize(event.target);
  sendButton.disabled = !event.target.value.trim() && !(typeof pendingScreenshot !== 'undefined' && pendingScreenshot);
  if (event.target === chatInput) $('#inputCount').textContent = `${event.target.value.length} / 500`;
}

function submitFrom(input) {
  if (actionLocked) return toast('正在处理上一条消息，请稍候');
  const text = input.value;
  const attachment = typeof pendingScreenshot !== 'undefined' ? pendingScreenshot : null;
  if (!text.trim() && !attachment) return;
  input.value = '';
  input.style.height = 'auto';
  heroSend.disabled = true;
  chatSend.disabled = true;
  $('#inputCount').textContent = '0 / 500';
  if (attachment) sendScreenshot(text, attachment);
  else beginConversation(text);
}

